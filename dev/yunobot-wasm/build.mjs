  for(let i=0;i<C*H;i++)adam(W2,gW2[i],mW2,vW2,i,1e-4);for(let i=0;i<C;i++)adam(b2,gB2[i],mB2,vB2,i);for(let i=0;i<H;i++)adam(b1,gB1[i],mB1,vB1,i);
