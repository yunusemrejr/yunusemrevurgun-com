   const dz=new Float32Array(H);
   for(let c=0;c<C;c++){const d=(p[c]-((c===it.label?1-SMOOTH:0)+SMOOTH/C))*wgt;gB2[c]+=d;const row=c*H;for(let j=0;j<H;j++){gW2[row+j]+=d*h[j];dz[j]+=d*W2[row+j];}}
